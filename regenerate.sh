#!/usr/bin/env bash
# Regenerate the classics pack from the original Microsoft files (A-PACK-2, A-ID-1, A-THEME-1).
#
#   BENTWIRE_REFERENCE=$BENTWIRE_REFERENCE BENTWIRE_SOURCES=~/Sources/bentwire \
#     characters/classics/regenerate.sh
#
# Converts every source that converts completely into <id>.bwc, extracts the Office balloon
# theme from OBALLOON.DLL, and rewrites README.md with the list of included and excluded
# sources. The source files are only read. Output is reproducible (byte-identical on rerun).
set -euo pipefail
for v in BENTWIRE_REFERENCE BENTWIRE_SOURCES; do
  if [ -z "${!v:-}" ]; then
    echo "NOT RUN: set $v"
    exit 77
  fi
done
here=$(cd "$(dirname "$0")" && pwd)
repo=$(cd "$here/../.." && pwd)
export PATH="$HOME/.cargo/bin:$PATH"
(cd "$repo" && cargo build --release -q -p bentwire-convert --bins)
bin="$repo/target/release"
tmp=$(mktemp -d)
trap 'rm -rf "${tmp:?}"' EXIT

palette="$BENTWIRE_SOURCES/MSO97.DLL"
mkdir -p "$tmp/out"
"$bin/gen-classics" "$BENTWIRE_REFERENCE" "$BENTWIRE_SOURCES" "$tmp/out" "$palette" \
  "$here/options.txt" > "$tmp/report.tsv"

find "$here" -maxdepth 1 -name '*.bwc' -delete
mv "$tmp"/out/*.bwc "$here/"

unzip -q -o "$BENTWIRE_SOURCES/the Office XP files" the Office XP files/OBALLOON.DLL -d "$tmp"
rm -rf "${here:?}/balloon-themes"
"$bin/bentwire-convert" --theme "$tmp/the Office XP files/OBALLOON.DLL" "$here/balloon-themes/office"

cat > "$here/pack.toml" <<'TOML'
name = "classics"
licence = "none: Microsoft characters, converted from the user's own files; see README.md"
provenance = "Generated by regenerate.sh from Microsoft Agent 2.0 (ACS, ACF/ACA), Agent 1.5 and Office 97 / Microsoft Bob (ACT) files and OBALLOON.DLL; see README.md"
description = "Microsoft Agent and Office Assistant characters plus the Office balloon theme"
TOML

{
  cat <<'MD'
# classics

Microsoft Agent and Office Assistant characters converted into the bentwire format, plus the
Office balloon theme (`balloon-themes/office`, from `OBALLOON.DLL` 10.0.2607 in
`the Office XP files`). Everything here is generated by `regenerate.sh` from the original files;
nothing outside this folder refers to it. bentwire's code carries no licence for these
files: they are Microsoft's and are kept here only so the owner can run bentwire with the
characters they own. The pack is meant to be split into its own repository.

Regenerate:

    BENTWIRE_REFERENCE=$BENTWIRE_REFERENCE BENTWIRE_SOURCES=~/Sources/bentwire \
      characters/classics/regenerate.sh

Rules: a source goes in when it converts and `source.missing_animations` is empty
(A-PACK-2); ids follow A-ID-1 (ACS: file stem; web: `-web`; Agent 1.5: `-15`; ACT: `-97`
Office 97, `-bob` Microsoft Bob, `-act` other; a parenthesised qualifier in the file name,
as in `ROCKY(Greetings).ACT`, is kept only when two sources would otherwise share an id);
byte-identical sources are converted once.
The Office palette for ACT bitmap actors is read from `MSO97.DLL` 8.0.3507 of the Office 97
CD at conversion time; vector actors are rasterised by bentwire's WMF rasteriser (1x and 2x,
aliased). Each `.bwc` names its source file and SHA-256 prefix in `[source]`.

Size: vector actors carry a 2x hidpi sheet next to the 1x sheet (D2 allows it), so they are
the one case larger than their source: Office 97 Clippit 361 kB (1x) + 954 kB (2x) against
a 468 kB `.ACT` (about 2.8x, in line with the 2.6x estimate of character-format 12.5); Will
(Bob and Office 97) about 6x its `.ACT`. Bitmap and Agent characters are smaller than their
sources.

## Included

| id | source | bytes |
|---|---|---|
MD
  awk -F'\t' '$1 == "included" { printf "| %s | `%s` | %d |\n", $2, $3, $4 }' "$tmp/report.tsv"
  cat <<'MD'

## Excluded

| source | reason |
|---|---|
MD
  awk -F'\t' '$1 == "excluded" || $1 == "duplicate" { printf "| `%s` | %s |\n", $2, $3 }' "$tmp/report.tsv"
} > "$here/README.md"

awk -F'\t' '$1 == "excluded" { print "excluded: " $2 ": " $3 }' "$tmp/report.tsv"
echo "included: $(grep -c '^included' "$tmp/report.tsv") characters"
