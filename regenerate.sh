#!/usr/bin/env bash
# Regenerate the classics pack from the original Microsoft files (A-PACK-2, A-ID-1, A-THEME-1).
#
#   BENTWIRE_REFERENCE=... BENTWIRE_SOURCES=... [BENTWIRE_BIN=<dir with bentwire-convert>] \
#     ./regenerate.sh
#
# Converts every source that converts completely into <id>.bwc, extracts the Office balloon
# theme from OBALLOON.DLL, and writes CONTENTS.md with the list of included and excluded
# sources. The converter is $BENTWIRE_BIN/bentwire-convert, else bentwire-convert on PATH.
# The source files are only read. Output is reproducible (byte-identical on rerun).
set -euo pipefail
for v in BENTWIRE_REFERENCE BENTWIRE_SOURCES; do
  if [ -z "${!v:-}" ]; then
    echo "NOT RUN: set $v"
    exit 77
  fi
done
here=$(cd "$(dirname "$0")" && pwd)
if [ -n "${BENTWIRE_BIN:-}" ]; then
  convert="$BENTWIRE_BIN/bentwire-convert"
else
  convert=$(command -v bentwire-convert || true)
fi
if [ ! -x "${convert:-}" ]; then
  echo "error: bentwire-convert not found (set BENTWIRE_BIN or put it on PATH)" >&2
  exit 1
fi
tmp=$(mktemp -d)
trap 'rm -rf "${tmp:?}"' EXIT

"$here/sources.sh" > "$tmp/sources.txt"
mkdir -p "$tmp/out"
"$convert" --office-palette "$("$here/sources.sh" --palette)" \
  --batch "$tmp/sources.txt" "$tmp/out" --per-id "$here/options.txt" > "$tmp/report.abs"
# Report paths relative to the two input roots.
while IFS= read -r line; do
  line=${line//"$BENTWIRE_REFERENCE"/\$BENTWIRE_REFERENCE}
  printf '%s\n' "${line//"$BENTWIRE_SOURCES"/\$BENTWIRE_SOURCES}"
done < "$tmp/report.abs" > "$tmp/report.tsv"

find "$here" -maxdepth 1 -name '*.bwc' -delete
mv "$tmp"/out/*.bwc "$here/"

unzip -q -o "$BENTWIRE_SOURCES/the Office XP files" the Office XP files/OBALLOON.DLL -d "$tmp"
rm -rf "${here:?}/balloon-themes"
"$convert" --theme "$tmp/the Office XP files/OBALLOON.DLL" "$here/balloon-themes/office" \
  --generator "characters/classics/regenerate.sh" # the pack's old path, kept: theme.toml stays byte-identical

cat > "$here/pack.toml" <<'TOML'
name = "classics"
licence = "none: Microsoft characters, converted from the user's own files; see README.md"
provenance = "Generated by regenerate.sh from Microsoft Agent 2.0 (ACS, ACF/ACA), Agent 1.5 and Office 97 / Microsoft Bob (ACT) files and OBALLOON.DLL; see README.md"
description = "Microsoft Agent and Office Assistant characters plus the Office balloon theme"
TOML

{
  cat <<'MD'
# Contents

Generated by `regenerate.sh`; do not edit. Rules: see README.md.

## Included

| id | source | bytes |
|---|---|---|
MD
  awk -F'\t' '$1 == "included" { printf "| %s | `%s` | %d |\n", $2, $3, $4 }' "$tmp/report.tsv"
  cat <<'MD'

## Excluded

| source | reason |
|---|---|
MD
  awk -F'\t' '$1 == "excluded" || $1 == "duplicate" { printf "| `%s` | %s |\n", $2, $3 }' "$tmp/report.tsv"
} > "$here/CONTENTS.md"

awk -F'\t' '$1 == "excluded" { print "excluded: " $2 ": " $3 }' "$tmp/report.tsv"
echo "included: $(grep -c '^included' "$tmp/report.tsv") characters"
